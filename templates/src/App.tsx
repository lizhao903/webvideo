import { AutoStartGate } from "./components/AutoStartGate";
import { AutoToggle } from "./components/AutoToggle";
import { ProgressBar } from "./components/ProgressBar";
import { Stage } from "./components/Stage";
import { useAudioPlayer } from "./hooks/useAudioPlayer";
import { useAutoMode } from "./hooks/useAutoMode";
import { useRenderTimings } from "./hooks/useRenderTimings";
import { useStepper } from "./hooks/useStepper";
import { CHAPTERS } from "./registry/chapters";
import { COVERS } from "./covers/registry";

/**
 * Estimate spoken duration of a Chinese narration string. Native pace
 * ≈ 4 char/s → 250ms per char. Used as Auto-mode fallback ONLY when the
 * audio file is missing / fails / the narration is empty. When audio plays
 * normally, this value is unused — auto-advance fires on `audio.ended`.
 */
function estimateMs(text: string): number {
  if (!text) return 1500;
  return Math.max(1500, text.length * 250);
}

/**
 * Cover mode: when `?cover=<id>` is in the URL, render that cover variant
 * fullscreen at the configured STAGE_W × STAGE_H (or the override forced by
 * `?ratio=...`) instead of the normal Stage. Used by Playwright to screenshot
 * thumbnail variants (see scripts/render-covers.mjs).
 *
 * `COVERS` is always imported from `./covers/registry`, which the scaffold
 * writes as an empty array (`export const COVERS = []`) for new projects
 * without any cover variants. Phase 5 (`references/COVER.md`) fills it in.
 *
 * Returns null when no `?cover=` param is set → normal Stage takes over.
 */
function CoverMode() {
  const params = new URLSearchParams(window.location.search);
  const coverId = params.get("cover");
  if (!coverId) return null;
  const cover = COVERS.find((c) => c.id === coverId);
  if (!cover) {
    return (
      <div style={{ padding: 40, color: "#900", fontFamily: "monospace" }}>
        unknown cover id: {coverId}. Available:{" "}
        {COVERS.length === 0
          ? "(none — see references/COVER.md to add variants)"
          : COVERS.map((c) => c.id).join(", ")}
      </div>
    );
  }
  const Cmp = cover.Component;
  return <Cmp />;
}

export default function App() {
  const coverScene = CoverMode();
  if (coverScene) return coverScene;
  return <AppMain />;
}

function AppMain() {
  const stepper = useStepper(CHAPTERS);
  const ch = CHAPTERS[stepper.cursor.chapter]!;
  const Cmp = ch.Component;
  const stepText = ch.narrations[stepper.cursor.step] ?? "";

  const { mode, cycleMode, autoStarted, setAutoStarted } = useAutoMode();

  // Audio path follows the convention: /audio/<chapter-id>/<step+1>.mp3
  // (1-indexed file names match what `extract-narrations.ts` outputs.)
  // Empty narration → no audio src, Auto mode falls back to estimate.
  const audioSrc =
    mode === "manual" || stepText === ""
      ? null
      : `${import.meta.env.BASE_URL}audio/${ch.id}/${stepper.cursor.step + 1}.mp3`;

  const isLastStep =
    stepper.cursor.chapter === CHAPTERS.length - 1 &&
    stepper.cursor.step === CHAPTERS[CHAPTERS.length - 1]!.narrations.length - 1;

  const { onAutoAdvance } = useRenderTimings({
    mode,
    autoStarted,
    chapterId: ch.id,
    step: stepper.cursor.step,
    isLastStep,
    onAdvance: stepper.next,
  });

  useAudioPlayer({
    src: audioSrc,
    mode,
    trailMs: 200,
    estimateFallbackMs: estimateMs(stepText),
    onAutoAdvance,
    autoStarted,
  });

  return (
    <>
      <Stage onAdvance={stepper.next}>
        <div key={ch.id} className="scene">
          <Cmp step={stepper.cursor.step} />
        </div>
      </Stage>
      <ProgressBar
        chapters={CHAPTERS}
        cursor={stepper.cursor}
        onJumpChapter={stepper.jumpToChapter}
      />
      <AutoToggle mode={mode} onCycle={cycleMode} />
      <AutoStartGate
        visible={mode === "auto" && !autoStarted}
        onStart={() => setAutoStarted(true)}
      />
    </>
  );
}
